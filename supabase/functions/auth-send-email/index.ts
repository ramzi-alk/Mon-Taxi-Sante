// Supabase Auth "Send Email" hook — replaces Supabase's own (unreliable,
// wrong-sender-domain) mailer for every authentication email with a direct
// call to the Resend API, using the same sender/domain already verified
// (SPF+DKIM) for every other transactional email in this app (see
// src/lib/resend.ts). Once this hook is enabled in the Supabase dashboard,
// Supabase stops sending auth emails itself entirely — ALL of signup,
// recovery, magiclink (also used for the patient email-code lookup, see
// src/repositories/authRepository.ts), invite and email_change go through
// this function. So every type below has to be handled: silently missing
// one would silently break that flow (e.g. driver signup confirmation,
// password reset) instead of just falling back to Supabase's mailer.
//
// Payload + signature verification follow Supabase's documented "Send
// Email Hook" contract: https://supabase.com/docs/guides/auth/auth-hooks/send-email-hook
//
// Required function secrets (set via `supabase secrets set`, not doable
// from this repo/MCP — see README note below):
//   RESEND_API_KEY          — same key already used by the app's backend
//   SEND_EMAIL_HOOK_SECRET  — generated by Supabase when the hook is
//                              enabled in Dashboard > Authentication > Hooks,
//                              looks like "v1,whsec_<base64>"
// Optional:
//   RESEND_FROM_EMAIL       — defaults to the same address as the rest of
//                              the app (src/lib/resend.ts)

import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import { Webhook } from "https://esm.sh/standardwebhooks@1.0.0";

const RESEND_API_KEY = Deno.env.get("RESEND_API_KEY");
const HOOK_SECRET = Deno.env.get("SEND_EMAIL_HOOK_SECRET")?.replace("v1,whsec_", "");
const FROM_EMAIL = Deno.env.get("RESEND_FROM_EMAIL") || "Docteur Taxi <reservations@docteurtaxi.fr>";
const SUPPORT_EMAIL = "contact@mon-taxi-sante.com";
const SUPPORT_PHONE_DISPLAY = "06 02 12 19 07";
const SUPPORT_PHONE_TEL = "+33602121907";

interface HookUser {
  email: string;
  new_email?: string;
}

interface HookEmailData {
  token: string;
  token_hash: string;
  redirect_to: string;
  email_action_type: string;
  site_url: string;
  token_new: string;
  token_hash_new: string;
}

interface HookPayload {
  user: HookUser;
  email_data: HookEmailData;
}

// GoTrue's own verify endpoint — same one Supabase's default mailer links
// to, reconstructed here since the hook only gives us the token hash, not
// a ready-made URL. PROJECT_REF is stable per Supabase project (not a
// secret — it's the same value already embedded in VITE_SUPABASE_URL).
const PROJECT_REF = "jndiuqemysussvdiwcrk";

function confirmationUrl(tokenHash: string, type: string, redirectTo: string): string {
  const params = new URLSearchParams({ token: tokenHash, type, redirect_to: redirectTo });
  return `https://${PROJECT_REF}.supabase.co/auth/v1/verify?${params.toString()}`;
}

