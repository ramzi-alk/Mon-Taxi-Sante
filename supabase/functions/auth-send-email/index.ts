const ACTION_BADGE = { badge: "Action requise", badgeBg: "#EFF4FF", badgeColor: "#1244E8" };

function renderEmail(user: HookUser, emailData: HookEmailData): { subject: string; to: string; html: string } | null {
  const { email_action_type, redirect_to } = emailData;

  switch (email_action_type) {
    case "signup":
      return {
        subject: "Confirmez votre adresse e-mail — Docteur Taxi",
        to: user.email,
        html: shell({
          emoji: "✉️",
          heading: "Confirmez votre adresse e-mail",
          ...ACTION_BADGE,
          intro: "Merci de votre inscription sur Docteur Taxi. Confirmez votre adresse e-mail pour activer votre compte.",
          cta: {
            kind: "button",
            label: "Confirmer mon adresse e-mail",
            url: confirmationUrl(emailData.token_hash, email_action_type, redirect_to),
          },
          footnote: "Si vous n'êtes pas à l'origine de cette demande, vous pouvez ignorer cet e-mail.",
        }),
      };

    case "recovery":
      return {
        subject: "Réinitialisez votre mot de passe — Docteur Taxi",
        to: user.email,
        html: shell({
          emoji: "🔑",
          heading: "Réinitialisez votre mot de passe",
          ...ACTION_BADGE,
          intro:
            "Vous avez demandé la réinitialisation de votre mot de passe Docteur Taxi. Cliquez sur le bouton ci-dessous pour choisir un nouveau mot de passe.",
          cta: {
            kind: "button",
            label: "Réinitialiser mon mot de passe",
            url: confirmationUrl(emailData.token_hash, email_action_type, redirect_to),
          },
          footnote:
            "Ce lien est valable une heure. Si vous n'êtes pas à l'origine de cette demande, vous pouvez ignorer cet e-mail — votre mot de passe ne sera pas modifié.",
        }),
      };

    case "magiclink":
      // Also the type used for signInWithOtp email codes (patient history
      // lookup, PatientEmailLogin.tsx) — not just true magic links.
      return {
        subject: "Votre code de connexion — Docteur Taxi",
        to: user.email,
        html: shell({
          emoji: "🔑",
          heading: "Votre code de connexion",
          ...ACTION_BADGE,
          intro:
            "Saisissez ce code sur la page où vous avez demandé à vous connecter ou à retrouver votre historique de réservations Docteur Taxi.",
          cta: { kind: "code", value: emailData.token },
          footnote:
            "Ce code expire dans quelques minutes. Si vous n'êtes pas à l'origine de cette demande, vous pouvez ignorer cet e-mail.",
        }),
      };

    case "invite":
      return {
        subject: "Vous êtes invité(e) sur Docteur Taxi",
        to: user.email,
        html: shell({
          emoji: "🎉",
          heading: "Vous êtes invité(e)",
          badge: "Invitation",
          badgeBg: "#ECFDF5",
          badgeColor: "#059669",
          intro:
            "Vous avez été invité(e) à créer un compte sur Docteur Taxi. Cliquez sur le bouton ci-dessous pour choisir votre mot de passe et accéder à votre espace.",
          cta: {
            kind: "button",
            label: "Créer mon mot de passe",
            url: confirmationUrl(emailData.token_hash, email_action_type, redirect_to),
          },
          footnote: "Si vous ne vous attendiez pas à cette invitation, vous pouvez ignorer cet e-mail.",
        }),
      };

    case "email_change": {
      // Secure Email Change setting (Dashboard > Authentication > Providers)
      // decides whether one or two OTPs are issued — see the field-naming
      // caveat in Supabase's Send Email Hook docs: token_hash_new pairs
      // with the CURRENT email, token_hash pairs with the NEW one. This app
      // has no email-change UI today (only password updates, see
      // authRepository.ts), so this path isn't exercised in practice —
      // handled defensively so it doesn't silently break if that ever
      // changes.
      const toNewEmail = Boolean(emailData.token_hash);
      const to = toNewEmail ? user.new_email || user.email : user.email;
      const tokenHash = toNewEmail ? emailData.token_hash : emailData.token_hash_new;
      if (!to || !tokenHash) return null;
      return {
        subject: "Confirmez votre nouvelle adresse e-mail — Docteur Taxi",
        to,
        html: shell({
          emoji: "📧",
          heading: "Confirmez votre nouvelle adresse e-mail",
          ...ACTION_BADGE,
          intro: `Vous avez demandé à remplacer l'adresse e-mail de votre compte Docteur Taxi par <strong>${
            user.new_email || ""
          }</strong>. Confirmez ce changement en cliquant sur le bouton ci-dessous.`,
          cta: {
            kind: "button",
            label: "Confirmer la nouvelle adresse",
            url: confirmationUrl(tokenHash, email_action_type, redirect_to),
          },
          footnote:
            "Si vous n'êtes pas à l'origine de cette demande, vous pouvez ignorer cet e-mail — votre adresse actuelle restera inchangée.",
        }),
      };
    }

    default:
      // Notification-only types (reauthentication, password_changed_notification,
      // *_notification...) aren't triggered by any flow in this app (no MFA,
      // no reauthentication) — unhandled on purpose so a future use shows up
      // as a clear failure instead of a silently missing email.
      return null;
  }
}

Deno.serve(async (req) => {
  if (req.method !== "POST") {
    return new Response("Method not allowed", { status: 405 });
  }

  if (!RESEND_API_KEY || !HOOK_SECRET) {
    return new Response(
      JSON.stringify({ error: { message: "Missing RESEND_API_KEY or SEND_EMAIL_HOOK_SECRET secret" } }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }

  const payload = await req.text();
  const headers = Object.fromEntries(req.headers);

  let data: HookPayload;
  try {
    data = new Webhook(HOOK_SECRET).verify(payload, headers) as HookPayload;
  } catch {
    return new Response(JSON.stringify({ error: { message: "Invalid signature" } }), {
      status: 401,
      headers: { "Content-Type": "application/json" },
    });
  }

  const email = renderEmail(data.user, data.email_data);
  if (!email) {
    return new Response(
      JSON.stringify({ error: { message: `Unsupported email_action_type: ${data.email_data.email_action_type}` } }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }

  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${RESEND_API_KEY}`, "Content-Type": "application/json" },
      body: JSON.stringify({ from: FROM_EMAIL, to: [email.to], subject: email.subject, html: email.html }),
    });
    if (!res.ok) {
      const text = await res.text();
      throw new Error(`Resend API ${res.status}: ${text}`);
    }
  } catch (err) {
    return new Response(
      JSON.stringify({ error: { message: err instanceof Error ? err.message : String(err) } }),
      { status: 500, headers: { "Content-Type": "application/json" } }
    );
  }

  return new Response(JSON.stringify({}), { status: 200, headers: { "Content-Type": "application/json" } });
});
